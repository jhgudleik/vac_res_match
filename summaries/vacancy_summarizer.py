import pandas as pd
from typing import List, Dict, Optional
import time

from .base_generator import BaseSummaryGenerator
from .gemini_generator import GeminiSummaryGenerator
from .heuristic_generator import HeuristicSummaryGenerator
from .config import Config

class VacancySummarizer:
    """Основной класс для суммаризации вакансий"""

    def __init__(self, use_model: str = "auto"):
        """
        Инициализирует суммаризатор

        Args:
            use_model: "gemini", "heuristic" или "auto"
        """
        self.use_model = use_model
        self.generator = None

    def _get_generator(self) -> BaseSummaryGenerator:
        """Возвращает соответствующий генератор"""
        if self.generator is None:
            if self.use_model == "gemini":
                try:
                    self.generator = GeminiSummaryGenerator()
                except ValueError:
                    print("Gemini API недоступен, использую эвристический метод")
                    self.generator = HeuristicSummaryGenerator()
            elif self.use_model == "heuristic":
                self.generator = HeuristicSummaryGenerator()
            else:  # auto
                try:
                    self.generator = GeminiSummaryGenerator()
                except Exception:
                    print("Использую эвристический метод")
                    self.generator = HeuristicSummaryGenerator()

        return self.generator

    def summarize_vacancies(self, vacancies: List[Dict]) -> pd.DataFrame:
        """
        Создает саммари для датасета вакансий

        Args:
            vacancies: Список словарей с вакансиями

        Returns:
            DataFrame с саммари
        """
        print(f"Начинаем генерацию саммари для {len(vacancies)} вакансий...")

        generator = self._get_generator()
        results = generator.create_dataset_summaries(vacancies)

        # Добавляем паузы между запросами
        for i in range(1, len(results)):
            time.sleep(Config.REQUEST_DELAY)

        # Создаем DataFrame
        df = pd.DataFrame(results)

        # Статистика
        self._print_statistics(df)

        return df

    def summarize_single_vacancy(self, vacancy: Dict) -> Dict:
        """
        Создает саммари для одной вакансии

        Args:
            vacancy: Словарь с вакансией

        Returns:
            Словарь с результатом
        """
        generator = self._get_generator()
        text = vacancy.get("full_text", "")

        if not text or len(text) < 50:
            return {
                "success": False,
                "error": "Текст слишком короткий",
                "summary": ""
            }

        result = generator.generate_summary(text)

        return {
            "vacancy_id": vacancy.get("id", "unknown"),
            "title": vacancy.get("title", ""),
            **result
        }

    def _print_statistics(self, df: pd.DataFrame):
        """Выводит статистику обработки"""
        success_count = df["success"].sum()
        print(f"Готово! Успешно обработано: {success_count}/{len(df)}")

        if success_count > 0:
            avg_length = df[df["success"]]["summary"].str.len().mean()
            print(f"Средняя длина саммари: {avg_length:.0f} символов")

            model_counts = df["model_used"].value_counts()
            print("\nИспользованные модели:")
            for model, count in model_counts.items():
                print(f"  {model}: {count}")