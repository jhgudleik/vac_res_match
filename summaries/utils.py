import pandas as pd
from typing import List, Dict
import os

def save_summaries_to_csv(df: pd.DataFrame, filename: str = "vacancy_summaries.csv"):
    """Сохраняет саммари в CSV файл"""
    df.to_csv(filename, index=False, encoding='utf-8-sig')
    print(f"Результаты сохранены в {filename}")
    return filename

def load_summaries_from_csv(filename: str) -> pd.DataFrame:
    """Загружает саммари из CSV файла"""
    return pd.read_csv(filename, encoding='utf-8-sig')

def print_summary_results(df: pd.DataFrame, max_rows: int = 10):
    """Выводит результаты суммаризации"""
    print("\nРЕЗУЛЬТАТЫ ГЕНЕРАЦИИ:")

    for idx, row in df.head(max_rows).iterrows():
        if row["success"]:
            print(f"\nВАКАНСИЯ {idx+1}")
            print(f"Название: {row['title']}")
            print(f"Модель: {row['model_used']}")
            print(f"Время обработки: {row['processing_time']:.2f} сек")

            summary = row['summary']
            if len(summary) > 200:
                print(f"Саммари: {summary[:200]}...")
            else:
                print(f"Саммари: {summary}")

def export_to_excel(df: pd.DataFrame, filename: str = "vacancy_summaries.xlsx"):
    """Экспортирует результаты в Excel"""
    with pd.ExcelWriter(filename, engine='openpyxl') as writer:
        df.to_excel(writer, sheet_name='Summaries', index=False)

        # Создаем лист со статистикой
        stats = {
            'Metric': ['Total Vacancies', 'Successful', 'Failed', 'Average Summary Length'],
            'Value': [
                len(df),
                df['success'].sum(),
                len(df) - df['success'].sum(),
                df[df['success']]['summary'].str.len().mean()
            ]
        }
        pd.DataFrame(stats).to_excel(writer, sheet_name='Statistics', index=False)

    print(f"Результаты экспортированы в {filename}")