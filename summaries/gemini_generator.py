import os
import google.generativeai as genai
from typing import Dict
import time

from .base_generator import BaseSummaryGenerator
from .config import Config

class GeminiSummaryGenerator(BaseSummaryGenerator):
    """Генератор саммари с использованием Gemini API"""

    def __init__(self, api_key: str = None):
        super().__init__()
        self.summary_type = "gemini"
        self.api_key = api_key or Config.GEMINI_API_KEY

        if not self.api_key:
            raise ValueError("GEMINI_API_KEY не установлен")

        self._configure_gemini()

    def _configure_gemini(self):
        """Настраивает Gemini API"""
        genai.configure(api_key=self.api_key)
        self.model = genai.GenerativeModel('gemini-pro')

    def generate_summary(self, text: str) -> Dict:
        """Генерирует саммари используя Gemini API"""
        try:
            prompt = self._create_prompt(text[:Config.MAX_TEXT_LENGTH])

            response = self.model.generate_content(
                prompt,
                generation_config={
                    "temperature": Config.TEMPERATURE,
                    "top_p": 0.95,
                    "top_k": 40,
                    "max_output_tokens": Config.MAX_SUMMARY_LENGTH,
                }
            )

            return {
                "success": True,
                "summary": response.text.strip(),
                "type": self.summary_type,
                "error": ""
            }

        except Exception as e:
            return {
                "success": False,
                "summary": "",
                "type": f"{self.summary_type}_error",
                "error": str(e)
            }

    def _create_prompt(self, text: str) -> str:
        """Создает промт для суммаризации"""
        return f"""You are an HR specialist. Create a brief job vacancy summary in English using the following format:

REQUIRED QUALIFICATIONS:
• [main requirements]

PREFERRED QUALIFICATIONS:
• [additional requirements]

TECHNOLOGY STACK:
• [technologies and tools]

Extract only the most important information from the job description. Remove marketing phrases and working conditions descriptions.

Job description text:
{text}

Summary:"""