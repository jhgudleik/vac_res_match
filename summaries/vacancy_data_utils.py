def load_vacancies_from_csv(filepath: str) -> List[Dict[str, Any]]:
    """
    Загружает вакансии из CSV файла

    Args:
        filepath: Путь к CSV файлу

    Returns:
        Список вакансий в формате для суммаризатора
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Файл не найден: {filepath}")

    df = pd.read_csv(filepath)
    vacancies = []

    # Определяем колонки
    id_col = None
    title_col = None
    text_col = None

    # Ищем подходящие колонки
    for col in df.columns:
        col_lower = col.lower()
        if 'id' in col_lower:
            id_col = col
        elif 'title' in col_lower or 'name' in col_lower:
            title_col = col
        elif 'text' in col_lower or 'description' in col_lower or 'content' in col_lower:
            text_col = col

    # Если не нашли текстовую колонку, используем все колонки
    if text_col is None:
        text_col = df.columns[0]

    for idx, row in df.iterrows():
        vacancy = {
            "id": row[id_col] if id_col else f"vac_{idx+1:03d}",
            "title": row[title_col] if title_col else f"Vacancy {idx+1}",
            "text": str(row[text_col])
        }
        vacancies.append(vacancy)

    return vacancies


def load_vacancies_from_json(filepath: str) -> List[Dict[str, Any]]:
    """
    Загружает вакансии из JSON файла

    Args:
        filepath: Путь к JSON файлу

    Returns:
        Список вакансий
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Файл не найден: {filepath}")

    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Проверяем формат данных
    if isinstance(data, list):
        return data
    elif isinstance(data, dict):
        return [data]
    else:
        raise ValueError("Неверный формат JSON данных")


