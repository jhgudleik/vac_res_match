def export_to_excel(df: pd.DataFrame, filename: str = "vacancy_analysis.xlsx"):
    """
    Экспортирует результаты в Excel с несколькими листами

    Args:
        df: DataFrame с результатами
        filename: Имя файла Excel
    """
    try:
        with pd.ExcelWriter(filename, engine='openpyxl') as writer:
            # Основной лист
            df.to_excel(writer, sheet_name='Все вакансии', index=False)

            # Лист с высоким confidence
            high_conf = df[df['confidence_score'] > 0.7]
            if len(high_conf) > 0:
                high_conf.to_excel(writer, sheet_name='Высокая уверенность', index=False)

            # Лист с технологиями
            tech_data = []
            for idx, row in df.iterrows():
                if pd.notna(row['extracted_technologies']):
                    for tech in str(row['extracted_technologies']).split(','):
                        tech = tech.strip()
                        if tech:
                            tech_data.append({
                                'vacancy_id': row['vacancy_id'],
                                'vacancy_title': row['vacancy_title'],
                                'technology': tech,
                                'confidence': row['confidence_score']
                            })

            if tech_data:
                tech_df = pd.DataFrame(tech_data)
                tech_df.to_excel(writer, sheet_name='Технологии', index=False)

            # Лист со статистикой
            stats = {
                'Метрика': [
                    'Всего вакансий',
                    'Успешно обработано',
                    'Средняя уверенность',
                    'Средняя длина текста',
                    'Среднее время обработки',
                    'Вакансий с зарплатой',
                    'Удалённых вакансий',
                    'Гибридных вакансий'
                ],
                'Значение': [
                    len(df),
                    len(df[df['confidence_score'] > 0.3]),
                    df['confidence_score'].mean(),
                    df['source_text_length'].mean(),
                    df['processing_time'].mean(),
                    len(df[df['salary_info'].str.contains('\$', na=False)]),
                    len(df[df['location'] == 'Remote']),
                    len(df[df['location'] == 'Hybrid'])
                ]
            }
            stats_df = pd.DataFrame(stats)
            stats_df.to_excel(writer, sheet_name='Статистика', index=False)

        print(f"\n[ЭКСПОРТ] Результаты сохранены в Excel: {filename}")

    except Exception as e:
        print(f"[ОШИБКА] Не удалось сохранить в Excel: {e}")