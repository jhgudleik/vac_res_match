    @staticmethod
    def save_to_json(vacancies: List[Dict], filename: str):
        """Сохраняет вакансии в JSON файл"""
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(vacancies, f, ensure_ascii=False, indent=2)

    @staticmethod
    def load_from_dataframe(df, text_column: str = "full_text",
                           title_column: str = "title", id_column: str = "id") -> List[Dict]:
        """Загружает вакансии из DataFrame"""
        vacancies = []

        for idx, row in df.iterrows():
            vacancy = {
                "id": str(row.get(id_column, f"vac_{idx}")),
                "title": str(row.get(title_column, "")),
                "full_text": str(row.get(text_column, ""))
            }
            vacancies.append(vacancy)

        return vacancies