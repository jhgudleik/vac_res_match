from abc import ABC, abstractmethod
from typing import Dict, List
import time

class BaseSummaryGenerator(ABC):
    """Базовый класс для генерации саммари"""

    def __init__(self):
        self.summary_type = "base"

    @abstractmethod
    def generate_summary(self, text: str) -> Dict:
        """Генерирует саммари для текста"""
        pass

    def create_dataset_summaries(self, vacancies: List[Dict], **kwargs) -> List[Dict]:
        """Создает саммари для датасета вакансий"""
        results = []

        for i, vacancy in enumerate(vacancies, 1):
            text = vacancy.get("full_text", "")

            if not text or len(text) < 50:
                continue

            start_time = time.time()
            result = self.generate_summary(text)
            processing_time = time.time() - start_time

            result_dict = {
                "vacancy_id": vacancy.get("id", f"vac_{i}"),
                "title": vacancy.get("title", ""),
                "original_text_length": len(text),
                "model_used": self.summary_type,
                "summary": result.get("summary", ""),
                "summary_type": result.get("type", self.summary_type),
                "success": result.get("success", False),
                "error": result.get("error", ""),
                "processing_time": processing_time
            }

            results.append(result_dict)

        return results