import re
from typing import Dict, List

from .base_generator import BaseSummaryGenerator
from .config import Config

class HeuristicSummaryGenerator(BaseSummaryGenerator):
    """Эвристический генератор саммари"""

    def __init__(self):
        super().__init__()
        self.summary_type = "heuristic"

    def generate_summary(self, text: str) -> Dict:
        """Генерирует эвристическое саммари"""
        try:
            summary = self._heuristic_summary(text)
            return {
                "success": True,
                "summary": summary,
                "type": self.summary_type,
                "error": ""
            }
        except Exception as e:
            return {
                "success": False,
                "summary": "",
                "type": f"{self.summary_type}_error",
                "error": str(e)
            }

    def _heuristic_summary(self, text: str) -> str:
        """Эвристическая суммаризация"""
        sentences = re.split(r'[.!?]+', text)
        extracted = []

        for sentence in sentences:
            sentence = sentence.strip()
            if len(sentence) < 10:
                continue

            sentence_lower = sentence.lower()

            # Проверяем содержит ли ключевые слова
            if any(keyword in sentence_lower for keyword in Config.KEYWORDS):
                # Убираем маркетинговые фразы
                if not any(word in sentence_lower for word in Config.MARKETING_WORDS):
                    extracted.append(sentence)

        # Формируем структурированное саммари
        if extracted:
            summary = self._format_structured_summary(extracted)
        else:
            # Берем первые 3 предложения
            first_sentences = [s.strip() for s in sentences[:3] if len(s.strip()) > 10]
            summary = "Brief summary:\n• " + "\n• ".join(first_sentences)[:300]
            if len(first_sentences) > 0 and len(" ".join(first_sentences)) > 300:
                summary += "..."

        return summary

    def _format_structured_summary(self, sentences: List[str]) -> str:
        """Форматирует извлеченные предложения в структурированное саммари"""
        requirements = []
        technologies = []
        experience = []

        # Ключевые слова для классификации
        tech_keywords = [
            "python", "java", "javascript", "react", "docker", "kubernetes",
            "aws", "postgresql", "mysql", "mongodb", "typescript", "git",
            "jenkins", "terraform", "ansible", "linux", "sql", "nosql",
            "c++", "c#", "angular", "vue", "node.js", "express.js",
            "spring", "django", "flask", "fastapi", "ruby", "rails",
            "php", "laravel", "symfony", "go", "golang", "rust",
            "swift", "kotlin", "android", "ios", "flutter", "react native"
        ]

        exp_keywords = [
            "experience", "years", "year", "senior", "junior", "mid-level",
            "entry-level", "expert", "advanced", "intermediate", "beginner"
        ]

        # Классифицируем предложения
        for sentence in sentences:
            sentence_lower = sentence.lower()

            # Проверяем на технологии
            if any(tech in sentence_lower for tech in tech_keywords):
                technologies.append(sentence)
            # Проверяем на опыт
            elif any(exp in sentence_lower for exp in exp_keywords):
                experience.append(sentence)
            else:
                requirements.append(sentence)

        # Формируем структурированное саммари
        summary_parts = []

        if requirements:
            summary_parts.append("KEY REQUIREMENTS:")
            for req in requirements[:5]:
                summary_parts.append(f"• {req}")

        if technologies:
            summary_parts.append("\nTECHNOLOGY STACK:")
            unique_techs = self._extract_unique_technologies(technologies, tech_keywords)
            for tech in unique_techs[:10]:
                summary_parts.append(f"• {tech}")

        if experience:
            summary_parts.append("\nREQUIRED EXPERIENCE:")
            for exp in experience[:3]:
                summary_parts.append(f"• {exp}")

        if not summary_parts:
            summary_parts.append("Extracted summary:")
            for sentence in sentences[:3]:
                summary_parts.append(f"• {sentence}")

        return "\n".join(summary_parts)

    def _extract_unique_technologies(self, sentences: List[str], tech_keywords: List[str]) -> List[str]:
        """Извлекает уникальные технологии из предложений"""
        unique_techs = []
        for sentence in sentences:
            tech_words = []
            for keyword in tech_keywords:
                if keyword in sentence.lower():
                    # Правильное форматирование названий технологий
                    if keyword == "c++":
                        tech_words.append("C++")
                    elif keyword == "c#":
                        tech_words.append("C#")
                    elif keyword == "node.js":
                        tech_words.append("Node.js")
                    elif keyword == "express.js":
                        tech_words.append("Express.js")
                    elif keyword == "react native":
                        tech_words.append("React Native")
                    else:
                        tech_words.append(keyword.capitalize())
            if tech_words:
                unique_techs.extend(tech_words)

        return list(set(unique_techs))